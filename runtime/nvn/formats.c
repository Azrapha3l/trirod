// Return the guest memory footprint and block geometry used by Tegra texture layout code.
// Unsupported IDs use a four-byte color fallback so layout calculations retain a usable nonzero stride.
const FormatInfo *nvn_format_info(uint32_t format_id) {
    static const FormatInfo kUnknownFormat = {4, 1, 1, FMT_COLOR, NULL};
    if (format_id >= sizeof kFormatTable / sizeof kFormatTable[0] || !kFormatTable[format_id].bpb)
        return &kUnknownFormat;
    return &kFormatTable[format_id];
}

